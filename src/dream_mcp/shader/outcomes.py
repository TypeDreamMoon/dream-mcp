"""What a DreamShader reply actually means, when it is not about the source.

A compile that fails usually failed because the `.dsm` is wrong, and the message says so.
Three of DreamShader's refusals are not that: the source is fine, the *asset* is in a state
that makes rebuilding it unsafe, and the plugin stops instead of destroying something. They
read like compile errors and they are not.

That distinction is the whole reason this module exists. An agent handed
`Asset '...' has been edited by hand ...` with no framing will start editing the `.dsm` --
changing a file that was never wrong, to fix an asset it has not been told about. Naming the
refusal and the action it wants is worth more than any amount of message passthrough.

Matched on message text because that is all the bridge returns. The substrings are the stable
part of each message: the asset path, the source path and the counts vary, the clause does
not. A message that changes shape stops matching and falls through to `None`, which reports
the raw text -- the same thing that happened before this module existed.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Outcome:
    kind: str
    """Short slug, stable enough to branch on."""

    summary: str
    """One line: what state the asset is in."""

    action: str
    """What to do about it. The reason a caller reads this at all."""

    source_is_fine: bool = True
    """True when the `.dsm`/`.dsf` is not what needs changing. All three of these are."""


#: Ordered: the first match wins, so more specific clauses come first. In practice the three
#: are disjoint, but relying on that silently is how a reordering breaks something.
_RULES: tuple[tuple[str, Outcome], ...] = (
    (
        "has been edited by hand",
        Outcome(
            kind="diverged",
            summary=("The generated asset was edited by hand since DreamShader last wrote "
                     "it, so the rebuild was refused rather than destroying those edits."),
            action=("Decide which copy is the truth, on the asset's right-click menu under "
                    "DreamShader: 'Revert to Source' discards the hand edits and rebuilds, "
                    "'Adopt Into Source' rewrites the source file from the asset (backing "
                    "the old source up to <source>.bak), 'Detach From DreamShader' keeps "
                    "the asset and stops managing it. Do not edit the source to work around "
                    "this -- the source is not what changed."),
        ),
    ),
    (
        "is open in an asset editor",
        Outcome(
            kind="open-in-editor",
            summary=("The asset is open in an asset editor, which holds its own copy and "
                     "writes that copy back on Apply or Save -- so a rebuild now would be "
                     "silently reverted."),
            action="Close the asset editor window and run the same request again.",
        ),
    ),
    (
        "was not generated by DreamShader",
        Outcome(
            kind="foreign-asset",
            summary=("Something already exists at the target path that DreamShader did not "
                     "generate, so it was left alone."),
            action=("Rename the block in the source, or move/delete the existing asset. An "
                    "asset that was deliberately detached lands here too, and detaching is "
                    "permanent until you move one of the two."),
        ),
    ),
)

#: Deliberately absent: the write-owner deferral ("another editor owns this project's
#: DreamShader bridge"). It reads like it belongs here and cannot ever arrive here. Only a
#: NON-owning editor defers that way, and a non-owning editor consumes no bridge requests --
#: so it never answers one. The CLI is a separate process that owns nothing and defers to
#: nobody, so it never emits it either. A rule for it would be dead code with a passing test,
#: which is worse than no rule: it would read as coverage forever.


def classify(message: str | None) -> Outcome | None:
    """The refusal this message is, or None when it is an ordinary result."""
    if not message:
        return None
    for needle, outcome in _RULES:
        if needle in message:
            return outcome
    return None


#: What the plugin appends to a material's success message to say where it landed. Reading
#: this is better than restating the rule, because the plugin decides per asset and only it
#: knows which way the decision went.
_WROTE_TO_DISK = "(saved; the asset exists on disk)"
_MEMORY_ONLY = "(virtual)"


def persistence_note(message: str | None) -> str:
    """Where a successful compile put its output, said as precisely as the reply allows.

    Storage decides: an asset that already exists on disk is rebuilt AND SAVED even through
    the editor, and one that does not stays memory-only. This used to be a flat "the editor
    never writes `.uasset`", which was true until the plugin started letting the asset's own
    storage decide, and is now wrong in the direction that matters -- a caller told nothing
    was written, when something was.
    """
    if message:
        if _WROTE_TO_DISK in message:
            return ("The asset already existed on disk, so it was rebuilt AND SAVED there. "
                    "Pass report_writes=true to list every .uasset this run touched.")
        if _MEMORY_ONLY in message:
            return ("Memory-only: no .uasset was written, and none exists for this asset. "
                    "Use the CLI path (editor closed) if you need it on disk.")

    return ("Where the output landed depends on the asset, not on this being the warm path: "
            "one that already exists on disk is rebuilt and SAVED there, one that does not "
            "stays memory-only. Material function replies do not say which, so pass "
            "report_writes=true when it matters.")
