"""DreamShader refusals are not source errors, and must not read like them.

Three of the plugin's refusals mean "the asset is in a state that makes rebuilding it
unsafe", not "your `.dsm` is wrong". Handed the raw message, an agent starts editing the
source -- changing a file that was never wrong, to fix an asset it has not been told about.

The message strings are quoted from the plugin, so these tests also pin the coupling: if
DreamShader rewords one of them, the corresponding test fails here rather than the framing
silently disappearing from every reply.
"""

from __future__ import annotations

import pytest

from dream_mcp.shader import outcomes


# Quoted from DreamShaderGeneratedAssetMetadata.cpp / DreamShaderAssetFactory.cpp, with the
# variable parts filled in the way the plugin fills them.
DIVERGED = (
    "Asset '/Game/Materials/M_Emissive.M_Emissive' has been edited by hand since DreamShader "
    "generated it from 'DShader/Materials/M_Emissive.dsm', so it was NOT rebuilt (rebuilding "
    "would destroy those edits). Right-click the asset > DreamShader and choose one: 'Revert "
    "to Source' discards the edits and rebuilds, 'Adopt Into Source' rewrites "
    "'DShader/Materials/M_Emissive.dsm' from the edited asset, 'Detach From DreamShader' "
    "hands the asset over to you and stops managing it."
)
OPEN_IN_EDITOR = (
    "Asset '/Game/Materials/M_Emissive.M_Emissive' is open in an asset editor, so it was NOT "
    "rebuilt. An open editor works on its own copy of the asset and writes that copy back "
    "when you press Apply or Save, which would silently undo this rebuild. Close the editor "
    "and compile again."
)
FOREIGN = (
    "Asset '/Game/Materials/M_Emissive.M_Emissive' already exists and was not generated by "
    "DreamShader. Rename your shader or move/delete the existing asset before regenerating."
)


@pytest.mark.parametrize("message, kind", [
    (DIVERGED, "diverged"),
    (OPEN_IN_EDITOR, "open-in-editor"),
    (FOREIGN, "foreign-asset"),
])
def test_each_refusal_is_recognised(message, kind):
    outcome = outcomes.classify(message)
    assert outcome is not None, "the plugin reworded this message; update _RULES"
    assert outcome.kind == kind


@pytest.mark.parametrize("message", [DIVERGED, OPEN_IN_EDITOR, FOREIGN])
def test_every_refusal_says_the_source_is_not_the_problem(message):
    """The single most important property. Everything else here is wording."""
    outcome = outcomes.classify(message)
    assert outcome.source_is_fine
    assert outcome.action.strip()


def test_an_ordinary_compile_error_is_left_alone():
    """A real source error must fall through, or the framing becomes the lie instead."""
    message = ("I:/Project/DShader/M_Foo.dsm: Graph statement 1: unknown identifier "
               "'ThisIsNotDefined'.")
    assert outcomes.classify(message) is None


def test_the_write_owner_deferral_is_deliberately_not_a_rule():
    """It cannot reach a bridge reply, so a rule for it would be untestable coverage.

    Only a NON-owning editor defers this way, and a non-owning editor answers no bridge
    requests. Pinned so that adding the rule without first finding a path that delivers
    the message fails here.
    """
    message = ("Skipped /Game/M_X.M_X; another editor owns this project's DreamShader "
               "bridge, and only that one writes generated assets to disk.")
    assert outcomes.classify(message) is None


def test_nothing_matches_an_empty_or_missing_message():
    assert outcomes.classify(None) is None
    assert outcomes.classify("") is None


# ------------------------------------------------------------------ persistence

def test_a_saved_material_says_it_was_saved():
    """Storage decides, so an asset already on disk is rebuilt AND saved -- even warm.

    This is the claim that used to be flatly wrong in the other direction ("the editor
    generates in memory: no .uasset was written"), which told callers nothing had been
    written when something had.
    """
    note = outcomes.persistence_note(
        "Generated /Game/FX/M_Beam.M_Beam from I:/P/DShader/M_Beam.dsm."
        " (saved; the asset exists on disk)")
    assert "SAVED" in note
    assert "report_writes" in note


def test_a_virtual_material_says_nothing_was_written():
    note = outcomes.persistence_note(
        "Generated /Game/FX/M_Beam.M_Beam from I:/P/DShader/M_Beam.dsm. (virtual)")
    assert "no .uasset was written" in note


def test_a_reply_that_does_not_say_falls_back_to_the_rule():
    """Material function replies carry no marker, so the note must not guess either way."""
    note = outcomes.persistence_note(
        "Generated ShaderFunction /Game/Functions/MF_Tint.MF_Tint from I:/P/DShader/F.dsf.")
    assert "depends on the asset" in note
    assert "report_writes" in note


# ------------------------------------------------------------------ bridge ownership

def _shader_bridge(tmp_path):
    directory = tmp_path / "Saved/DreamShader/Bridge"
    directory.mkdir(parents=True)
    return directory


def test_the_owner_lock_names_who_serves_the_bridge(tmp_path):
    """One editor per project serves requests and writes assets; the lock says which.

    Worth reading separately from status.json even though the two normally agree: a caller
    asks this question precisely when writes are being skipped, and answering it from the
    file that only the owner writes would be circular.
    """
    from dream_mcp.core import liveness as live

    directory = _shader_bridge(tmp_path)
    (directory / "owner.lock").write_text(
        '{"pid": 4242, "heartbeat": "2026-08-20T11:36:39.947Z"}', encoding="utf-8")

    assert live._read_shader_owner(directory) == 4242


def test_a_missing_or_broken_lock_is_not_an_owner(tmp_path):
    """Absent is the ordinary case on an older plugin build, so it must not raise."""
    from dream_mcp.core import liveness as live

    directory = _shader_bridge(tmp_path)
    assert live._read_shader_owner(directory) is None

    (directory / "owner.lock").write_text("{not json", encoding="utf-8")
    assert live._read_shader_owner(directory) is None

    (directory / "owner.lock").write_text('{"pid": 0}', encoding="utf-8")
    assert live._read_shader_owner(directory) is None
